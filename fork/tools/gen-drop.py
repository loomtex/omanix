"""Generate fork/drop.txt: bin scripts that leave $OMARCHY_PATH/bin, plus the
hand-kept path globs in fork/drop-paths.txt. Run with python3 -I."""
import sys
import tomllib

classify, paths, out = sys.argv[1:4]
c = tomllib.load(open(classify, "rb"))
gone = sorted(b for b, k in c["bin"].items() if k in ("AGENT-INTENT", "DROP", "RE-EXPRESS-IN-NIX"))
with open(out, "w") as f:
    f.write("# Generated by fork/tools/gen-drop.py from classify.toml + drop-paths.txt.\n")
    f.write("# fnmatch globs relative to the omarchy tree; a glob matching a directory\n")
    f.write("# drops everything under it. Every glob must match something at the pin.\n\n")
    f.write(open(paths).read().rstrip() + "\n\n")
    f.write(f"# bin/: AGENT-INTENT, DROP and RE-EXPRESS-IN-NIX scripts ({len(gone)})\n")
    for b in gone:
        f.write(f"bin/{b}\n")
print(f"{len(gone)} bin scripts dropped")
