"""One-off generator: the pinned omarchy-menu.jsonc -> fork/intents.toml.

The disposition rules are DESIGN §h.5.1 and draft-fork.md appendix B, applied
to the ids at the pin (5978d93). intents.toml is the reviewed machine form;
regenerate only when moving the fork point, then review the diff.

  python3 -I gen-intents.py <pinned>/default/omarchy/omarchy-menu.jsonc > fork/intents.toml

Reads one JSONC file; executes nothing.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import jsonc  # noqa: E402

SKILLS = ["omanix-host", "onboarding", "apps", "defaults", "locale", "look", "themes",
          "shell-plugins", "add-plugin", "security", "boot", "network", "hardware", "update",
          "persist", "secrets", "diagnose-build", "diagnose-unit", "diagnose-crash", "recover",
          "rotate-keys", "reinstall"]

DROP = {
    "learn.community": "the omarchy Discord; omanix has its own channels (§f.2.8)",
    "learn.arch": "replaced by learn.nixos (fork/menu-extra.jsonc)",
    "setup.security.passwordless-sudo": "omanix has no passwordless sudo; the resident uses approval sudo (D8)",
    "setup.direct-boot": "loom owns boot (D7)",
    "setup.reset": "reinstall from the host repo instead (§g.8)",
    "install.aur": "no AUR on NixOS; packages come from nixpkgs",
    "update.config.plymouth": "the boot splash is generated by nix (omanix.theme.boot)",
    "update.time": "time is synced by NTP (systemd-timesyncd)",
}

# gui rows whose upstream action needs another command on omanix.
GUI_ACTION = {
    "setup.monitors": ("omarchy-shell shell summon omarchy.monitor",
                       "the monitor panel; monitors.lua is read-only (omanix.hyprland.monitors)"),
    "update.omarchy": ("systemctl start --no-block loom-update.service",
                       "runs the update check now; the result is an Update card (§h.5.1)"),
    "update.password.user": ("omarchy-shell omanix.approval passwd",
                             "human-only Change password dialog (§h.11)"),
    "update.password.drive": ("omarchy-launch-floating-terminal-with-presentation 'sudo loom unlock add passphrase'",
                              "human-only: loom unlock in the human's terminal (§h.11)"),
    "learn.omarchy": ("omarchy-launch-editor \"$OMARCHY_PATH/manual\"",
                      "the omarchy manual shipped read-only; omarchy.org links are removed (§f.2.8)"),
}
GUI_LABEL = {"update.omarchy": "Check for updates"}

DEFAULT_KIND = {"browser": "browser", "terminal": "terminal", "editor": "editor", "dictation": "dictation tool"}


def intent(eid, e):
    """(text, skill, manual, touches, extra) for an AGENT-INTENT row, or None."""
    label = e.get("label", "")
    p = eid.split(".")
    if eid.startswith("setup.default.") and len(p) == 4 and p[2] in DEFAULT_KIND:
        return (f"Make {{label}} my default {DEFAULT_KIND[p[2]]}.", "defaults",
                f"configuration.nix: omanix.defaults.{p[2]} = \"{p[3]}\";", [f"omanix.defaults.{p[2]}"], {})
    if eid.startswith("appearance.top-bar.indicators.clock."):
        return ("Show the bar clock as {label}.", "look",
                "configuration.nix: omanix.shell.settings (bar.layout clock format)", ["omanix.shell.settings"], {})
    if eid.startswith("appearance.branding."):
        what = "About screen" if p[2] == "about" else "screensaver"
        text = {"text": f"Change the text on my {what} to: ",
                "image": f"Use an image for my {what}: ",
                "default": f"Put back the default {what} branding."}[p[3]]
        return (text, "look", f"configuration.nix: omanix.branding.{p[2]}", [f"omanix.branding.{p[2]}"], {})
    if eid == "appearance.unlock":
        return ("Set the unlock screen to {selection}", "themes",
                "configuration.nix: omanix.theme.boot = \"<theme>\";", ["omanix.theme.boot"], {})
    if eid == "setup.keybindings":
        return ("Change a keybinding: ", "look",
                "configuration.nix: omanix.keybinds.binds.<name> (omanix edit hypr/bindings.lua for this session)",
                ["omanix.keybinds"], {"when": ""})
    if eid == "setup.input":
        return ("Change my mouse and touchpad settings: ", "look",
                "configuration.nix: omanix.hyprland.settings.input (omanix edit hypr/input.lua for this session)",
                ["omanix.hyprland.settings"], {"when": ""})
    if eid == "setup.typing.input":
        return ("Set up input methods for {selection}", "locale",
                "configuration.nix: omanix.input.methods", ["omanix.input"], {})
    if eid == "setup.language":
        return ("Switch my language to {label}.", "locale",
                "configuration.nix: omanix.language = \"{value}\";", ["omanix.language"], {})
    if eid == "update.kernel":
        return ("Boot the {label} kernel by default.", "boot",
                "configuration.nix: boot.kernelPackages = pkgs.{value};", ["boot.kernelPackages"], {"when": ""})
    if eid == "update.timezone":
        return ("Set my timezone to {label}.", "locale",
                "configuration.nix: loom.locale.timeZone = \"{value}\";", ["loom.locale.timeZone"],
                {"provider": "timezones"})
    if eid.startswith("setup.network.dns."):
        txt = "Use DNS from DHCP." if p[3] == "dhcp" else ("Use custom DNS servers: " if p[3] == "custom" else "Use {label} DNS.")
        return (txt, "network", f"configuration.nix: omanix.dns.provider = \"{label}\";", ["omanix.dns"], {})
    if eid.startswith("setup.plugin.") and p[2] in ("add", "clone", "remove"):
        verb = {"add": "Add", "clone": "Clone", "remove": "Remove"}[p[2]]
        return (f"{verb} a shell plugin: ", "shell-plugins",
                "configuration.nix: omanix.shell.plugins.<name>.src = inputs.<name>;", ["omanix.shell.plugins"],
                {"when": ""} if p[2] == "remove" else {})
    if eid.startswith("setup.security."):
        return ("Set up {label} on this computer.", "security", f"configuration.nix: (security skill: {p[2]})", [],
                {"when": ""} if p[2] == "sudoless-docker" else {})
    if eid == "setup.config.git":
        return ("Set my git name and email: ", "omanix-host", "home.nix: programs.git.settings.user", ["programs.git"], {})
    if eid.startswith("setup.config."):
        return ("Change my {label} configuration: ", "look",
                f"omanix edit {'hypr/hyprland.lua' if p[2] == 'hyprland' else p[2]} (this session) or the option it names",
                [], {})
    if eid == "install.style.theme":
        return ("Install a theme: ", "themes", "flake.nix input + configuration.nix: omanix.theme.extra", ["omanix.theme.extra"], {})
    if eid == "remove.theme":
        return ("Remove a theme: ", "themes", "configuration.nix: omanix.theme.extra", ["omanix.theme.extra"], {})
    if eid == "update.themes":
        return ("Update my extra themes.", "themes", "nix flake update <theme inputs>", [], {"when": ""})
    if eid.startswith("install.style.font."):
        return ("Install the {label} font.", "apps", "home.nix: home.packages = [ pkgs.nerd-fonts.<name> ];", ["home.packages"], {})
    if eid.startswith("remove.security."):
        return ("Turn off {label} on this computer.", "security", f"configuration.nix: (security skill: {p[2]})", [],
                {"when": ""} if p[2] == "sudoless-docker" else {})
    if eid in ("install.package", "remove.package"):
        verb = "Install" if p[0] == "install" else "Remove"
        return (f"{verb} a package: ", "apps", "home.nix: home.packages", ["home.packages"], {})
    if eid in ("install.webapp", "remove.webapp", "install.tui", "remove.tui"):
        what = "web app" if p[1] == "webapp" else "TUI"
        verb = "Install" if p[0] == "install" else "Remove"
        return (f"{verb} a {what}: ", "apps", f"configuration.nix: omanix.apps.{p[1]}s.<Name>", [f"omanix.apps.{p[1]}s"], {})
    if eid.startswith("install."):
        return ("Install {label}.", "apps", "omanix app add <name> (or home.packages in home.nix)", [], {})
    if eid.startswith("remove."):
        return ("Remove {label}.", "apps", "omanix app remove <name>", [], {})
    if eid.startswith("update.channel."):
        return ("Move this computer to the omanix {label} release line.", "update",
                "flake.nix: the omanix input's ref", ["inputs.omanix"], {})
    if eid == "update.firmware":
        return ("Check for firmware updates for this computer.", "update", "services.fwupd.enable = true; then fwupdmgr", [], {})
    return None


GUI_PREFIXES = ("apps", "about", "system.", "learn.", "appearance.", "trigger.", "setup.typing.keyboard",
                "setup.network.qr", "setup.plugin.enable", "setup.plugin.disable", "install.style.background",
                "update.process.", "update.hardware.", "update.config.", "update.password.", "update.omarchy",
                "setup.monitors")


def q(s):
    return json.dumps(s, ensure_ascii=False)


def main(path):
    m = json.loads(jsonc.drop_trailing_commas(jsonc.strip(open(path, encoding="utf-8").read())))
    out = [
        "# Every actionable row of the pinned omarchy-menu.jsonc (5978d93) -> gui | intent | drop",
        "# (DESIGN §h.5.1). Generated by fork/tools/gen-intents.py, then reviewed; keyed by the",
        "# upstream id. Provider-backed submenus have one row for all their runtime rows.",
        "# checks.menu-intents fails on a missing or stale row, an empty or unknown skill, a",
        "# template field other than {label} {value} {selection}, or a gui action that calls",
        "# a script omanix does not ship.",
        "#",
        "# Fields: kind; intent rows: text, skill, manual (the Do-it-yourself hint), touches",
        "# (informational), and optional overrides of the upstream row (when, provider);",
        "# gui rows: optional action/label overrides; drop rows: why.",
        "",
        "[defaults]",
        "send = false   # pre-fill only; the human presses Enter",
        "",
        "[skills]",
        "known = [" + ", ".join(q(s) for s in SKILLS) + "]",
        "",
    ]
    for eid, e in m.items():
        if not e.get("action") and not e.get("provider"):
            continue  # a submenu: navigation, emitted unchanged
        if eid.startswith("setup.default.agent."):
            out += [f"[entry.{q(eid)}]", 'kind = "drop"',
                    'why = "the default agent on omanix is the resident; the human picks their own harness in a terminal"', ""]
            continue
        if eid in DROP:
            out += [f"[entry.{q(eid)}]", 'kind = "drop"', f"why = {q(DROP[eid])}", ""]
            continue
        r = intent(eid, e)
        if r and not (eid.startswith(GUI_PREFIXES) and not eid.startswith(
                ("appearance.top-bar.indicators.clock.", "appearance.branding.", "appearance.unlock"))):
            text, skill, manual, touches, extra = r
            out += [f"[entry.{q(eid)}]", 'kind = "intent"', f"text = {q(text)}", f"skill = {q(skill)}",
                    f"manual = {q(manual)}"]
            if touches:
                out.append("touches = [" + ", ".join(q(t) for t in touches) + "]")
            for k, v in extra.items():
                out.append(f"{k} = {q(v)}")
            out.append("")
            continue
        if not eid.startswith(GUI_PREFIXES):
            raise SystemExit(f"no rule for {eid}")
        out += [f"[entry.{q(eid)}]", 'kind = "gui"']
        if eid in GUI_ACTION:
            act, why = GUI_ACTION[eid]
            out += [f"action = {q(act)}", f"why = {q(why)}"]
        if eid in GUI_LABEL:
            out.append(f"label = {q(GUI_LABEL[eid])}")
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
