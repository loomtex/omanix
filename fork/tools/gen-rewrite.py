"""Generate fork/rewrite.toml from a built-but-unrewritten omarchy-src tree.
Run with python3 -I. Reads files only.

Rules (§f.2.4 stage 5; facts §5):
  /usr/share/omarchy                     -> /run/current-system/omarchy  (OMARCHY_PATH)
  /usr/lib/omarchy-hyprland-titlebars/titlebars.so -> /etc/omanix/hyprland-titlebars.so
  /usr/bin/omarchy-<x>                   -> /run/current-system/omarchy/bin/omarchy-<x>
  /usr/bin/<x>                           -> /run/current-system/sw/bin/<x>
Shebang lines are left to patchShebangs. Anything else stays and is tracked in
residual.toml.
"""
import os
import re
import sys

RULES = [
    (r"/usr/share/omarchy(?![A-Za-z0-9_-])", "/run/current-system/omarchy"),
    (r"/usr/lib/omarchy-hyprland-titlebars/titlebars\.so", "/etc/omanix/hyprland-titlebars.so"),
    (r"/usr/bin/(omarchy-[a-z0-9][a-z0-9-]*[a-z0-9])(?![A-Za-z0-9_-])", r"/run/current-system/omarchy/bin/\1"),
    (r"/usr/bin/(?!omarchy-)([A-Za-z0-9_][A-Za-z0-9_.+-]*[A-Za-z0-9_+])(?![A-Za-z0-9_.+-])", r"/run/current-system/sw/bin/\1"),
]

tree = sys.argv[1]
print("# Generated by fork/tools/gen-rewrite.py against the pinned tree after drop/add/patch.")
print("# Exact counts: a mismatch fails the omarchy-src build (§f.2.4 stage 5).\n")
total = 0
for root, dirs, files in os.walk(tree):
    dirs.sort()
    for fn in sorted(files):
        path = os.path.join(root, fn)
        rel = os.path.relpath(path, tree)
        if os.path.islink(path):
            continue
        try:
            text = open(path, encoding="utf-8").read()
        except UnicodeDecodeError:
            continue
        lines = text.split("\n")
        body = "\n".join(lines[1:] if lines[0].startswith("#!") else lines)
        for rx, to in RULES:
            n = len(re.findall(rx, body))
            if n:
                total += n
                fr = rx.replace("\\", "\\\\").replace('"', '\\"')
                t = to.replace("\\", "\\\\")
                print(f'[[rewrite]]\nfile = "{rel}"\nregex = true\nfrom = "{fr}"\nto = "{t}"\ncount = {n}\n')
                body = re.sub(rx, to, body)
print(f"# {total} sites", file=sys.stderr)
